def analysis_rows(paragraph: dict, index: int) -> list[list[str]]:
    a = {str(k): str(v) for k, v in paragraph.get("analysis", [])}
    ideas = a.get("الفكرة الرئيسة", paragraph["idea"])
    supporting = a.get("أفكار داعمة", a.get("تطور الحدث", a.get("انتقال الفكرة", "الأحداث والأدلة الواردة تدعم الفكرة الرئيسة وتوضحها.")))
    direct = a.get("المعنى المباشر", "المعنى الصريح الذي تعرضه الفقرة في أحداثها وعباراتها.")
    implicit = a.get("المعنى الضمني", "الأخلاق الحقيقية تظهر حين يواجه الإنسان إغراءً أو ضغطًا.")
    structure = a.get("بناء الفقرة", a.get("تطور الحدث", a.get("انتقال الفكرة", a.get("العلاقة بما قبلها", "تنظيم منطقي يربط الفكرة بالدليل والنتيجة."))))
    purpose = a.get("الغرض", "الإخبار والإقناع والتوجيه إلى قيمة أخلاقية عملية.")
    judgement = a.get("الحكم", "الفقرة واضحة ومؤثرة؛ لأنها تربط المعنى بالدليل والموقف.")
    evidence = paragraph["values"][0][1] if paragraph.get("values") else paragraph["text"][:80]
    values = "، ".join(v[0] for v in paragraph.get("values", []))
    audience = [
        "الشباب والطلاب والأسر؛ لأن الفقرة تشرح أثر التربية وحماية الشباب.",
        "الشباب والرياضيون والطلاب؛ لأنها تعرض قرارًا أخلاقيًا تحت ضغط المنافسة.",
        "الشباب والمربون وكل من يظن أن النجاح يقاس بالجوائز وحدها.",
        "الشباب والمدارس والمجتمع الرياضي؛ لأنها تحول القصة إلى قاعدة تربوية واجتماعية.",
        "الشباب خاصة وكل قارئ يواجه اختبارًا أخلاقيًا في النجاح أو الإخفاق.",
    ][index]
    return [
        ["١ ـ نوع النص", a.get("نوع النص في الفقرة", "نص معلوماتي قصصي إقناعي؛ يجمع بين الواقعة الحقيقية والسرد والاستدلال.")],
        ["٢ ـ فكر النص", f"الفكرة الرئيسة: {ideas} الأفكار الداعمة: {supporting} المعنى المباشر: {direct} المعنى الضمني: {implicit}"],
        ["٣ ـ بنية النص", structure],
        ["٤ ـ الجمهور المستهدف", audience],
        ["٥ ـ غرض النص", purpose],
        ["٦ ـ تذوق النص ونقده والحكم عليه", judgement + " ومن جوانب القوة مناسبة اللغة للموقف وتنوع الأدلة ووضوح الأثر."],
        ["٧ ـ الاستدلال من النص", f"الدليل: {evidence}"],
        ["٨ ـ القيم المتضمنة وتطبيقاتها الحياتية", f"القيم: {values}. التطبيق: {ANALYSIS_APPLICATIONS[index]}"],
    ]


