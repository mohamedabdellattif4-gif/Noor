def add_general_section(doc, title, items, answers, mode, source=None):
    add_subheading(doc, title, TEAL)
    if mode == "mcq":
        for i, (q, opts, a) in enumerate(items, 1):
            add_question(doc, i, q + "  " + " ـ ".join(opts), a if answers else None, source, 1)
    else:
        for i, item in enumerate(items, 1):
            q, a = item
            add_question(doc, i, q, a if answers else None, source, 2 if mode != "essay" else 3)


