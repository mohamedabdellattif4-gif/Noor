AR_DIGITS = str.maketrans("0123456789", "٠١٢٣٤٥٦٧٨٩")


def ar_num(value: int) -> str:
    return str(value).translate(AR_DIGITS)


def load_paragraphs() -> list[dict]:
    src_path = Path("rebuilt-lesson2/build_lesson2_rebuilt.py")
    source = src_path.read_text(encoding="utf-8")
    # Repair two historical missing closing brackets without changing the source file.
    source = re.sub(r'(\["الحكم",\s*"[^\"]*")\s*\n\s*\],', r'\1]\n        ],', source)
    namespace = {"__name__": "lesson2_data"}
    exec(compile(source, str(src_path), "exec"), namespace)
    return namespace["PARAGRAPHS"]


def shade(cell, fill: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = tc_pr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tc_pr.append(shd)
    shd.set(qn("w:fill"), fill)


def borders(cell, color: str = "A9B8C6", size: str = "5") -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_borders = tc_pr.find(qn("w:tcBorders"))
    if tc_borders is None:
        tc_borders = OxmlElement("w:tcBorders")
        tc_pr.append(tc_borders)
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        el = tc_borders.find(qn(f"w:{edge}"))
        if el is None:
            el = OxmlElement(f"w:{edge}")
            tc_borders.append(el)
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), size)
        el.set(qn("w:color"), color)


def set_cell_margins(cell, top=90, start=110, bottom=90, end=110) -> None:
    tc = cell._tc
    tc_pr = tc.get_or_add_tcPr()
    tc_mar = tc_pr.first_child_found_in("w:tcMar")
    if tc_mar is None:
        tc_mar = OxmlElement("w:tcMar")
        tc_pr.append(tc_mar)
    for m, value in (("top", top), ("start", start), ("bottom", bottom), ("end", end)):
        node = tc_mar.find(qn(f"w:{m}"))
        if node is None:
            node = OxmlElement(f"w:{m}")
            tc_mar.append(node)
        node.set(qn("w:w"), str(value))
        node.set(qn("w:type"), "dxa")


def table_rtl(table) -> None:
    tbl_pr = table._tbl.tblPr
    bidi = tbl_pr.find(qn("w:bidiVisual"))
    if bidi is None:
        bidi = OxmlElement("w:bidiVisual")
        tbl_pr.append(bidi)
    bidi.set(qn("w:val"), "1")


def paragraph_rtl(p, alignment=WD_ALIGN_PARAGRAPH.RIGHT) -> None:
    p.alignment = alignment
    p_pr = p._p.get_or_add_pPr()
    bidi = p_pr.find(qn("w:bidi"))
    if bidi is None:
        bidi = OxmlElement("w:bidi")
        p_pr.append(bidi)
    bidi.set(qn("w:val"), "1")
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.line_spacing = 1.18


def style_run(run, size=13.0, bold=False, color=DARK, font="Arial") -> None:
    run.font.name = font
    run.font.size = Pt(size)
    run.bold = bold
    run.font.color.rgb = RGBColor.from_string(color)
    r_pr = run._r.get_or_add_rPr()
    fonts = r_pr.find(qn("w:rFonts"))
    if fonts is None:
        fonts = OxmlElement("w:rFonts")
        r_pr.append(fonts)
    for key in ("ascii", "hAnsi", "cs", "eastAsia"):
        fonts.set(qn(f"w:{key}"), font)
    rtl = r_pr.find(qn("w:rtl"))
    if rtl is None:
        rtl = OxmlElement("w:rtl")
        r_pr.append(rtl)
    rtl.set(qn("w:val"), "1")


def add_text(doc, text, size=13, bold=False, color=DARK, center=False, justify=False, after=4):
    p = doc.add_paragraph()
    paragraph_rtl(p, WD_ALIGN_PARAGRAPH.CENTER if center else (WD_ALIGN_PARAGRAPH.JUSTIFY if justify else WD_ALIGN_PARAGRAPH.RIGHT))
    p.paragraph_format.space_after = Pt(after)
    r = p.add_run(text)
    style_run(r, size=size, bold=bold, color=color)
    return p


def add_heading(doc, text, color=NAVY, level=1):
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table_rtl(table)
    cell = table.cell(0, 0)
    shade(cell, color)
    borders(cell, color, "4")
    set_cell_margins(cell, 110, 140, 110, 140)
    p = cell.paragraphs[0]
    paragraph_rtl(p, WD_ALIGN_PARAGRAPH.CENTER if level == 1 else WD_ALIGN_PARAGRAPH.RIGHT)
    r = p.add_run(text)
    style_run(r, size=19 if level == 1 else 15.5, bold=True, color=WHITE)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)


def add_subheading(doc, text, color=TEAL):
    p = doc.add_paragraph()
    paragraph_rtl(p)
    p.paragraph_format.space_before = Pt(7)
    p.paragraph_format.space_after = Pt(3)
    r = p.add_run(text)
    style_run(r, size=15, bold=True, color=color)
    p_pr = p._p.get_or_add_pPr()
    p_bdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "9")
    bottom.set(qn("w:color"), color)
    p_bdr.append(bottom)
    p_pr.append(p_bdr)


def add_box(doc, title, body, fill=PALE_BLUE, border=TEAL, title_color=TEAL):
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table_rtl(table)
    cell = table.cell(0, 0)
    shade(cell, fill)
    borders(cell, border, "7")
    set_cell_margins(cell, 120, 150, 120, 150)
    p = cell.paragraphs[0]
    paragraph_rtl(p, WD_ALIGN_PARAGRAPH.JUSTIFY)
    a = p.add_run(title + ": ")
    style_run(a, 13.5, True, title_color)
    b = p.add_run(body)
    style_run(b, 13.5, False, DARK)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)


def add_table(doc, headers, rows, header_fill=NAVY, widths=None, font_size=11.2):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = widths is None
    table_rtl(table)
    hdr = table.rows[0]
    tr_pr = hdr._tr.get_or_add_trPr()
    repeat = OxmlElement("w:tblHeader")
    repeat.set(qn("w:val"), "true")
    tr_pr.append(repeat)
    for i, header in enumerate(headers):
        cell = hdr.cells[i]
        shade(cell, header_fill)
        borders(cell, NAVY, "5")
        set_cell_margins(cell)
        if widths:
            cell.width = Cm(widths[i])
        p = cell.paragraphs[0]
        paragraph_rtl(p, WD_ALIGN_PARAGRAPH.CENTER)
        r = p.add_run(str(header))
        style_run(r, font_size, True, WHITE)
    for idx, row_data in enumerate(rows):
        row = table.add_row()
        for i, value in enumerate(row_data):
            cell = row.cells[i]
            shade(cell, WHITE if idx % 2 == 0 else GRAY)
            borders(cell)
            set_cell_margins(cell)
            if widths:
                cell.width = Cm(widths[i])
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            p = cell.paragraphs[0]
            paragraph_rtl(p, WD_ALIGN_PARAGRAPH.RIGHT)
            r = p.add_run(str(value))
            style_run(r, font_size, False, DARK)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return table


def add_bullets(doc, items, color=DARK):
    for item in items:
        p = doc.add_paragraph()
        paragraph_rtl(p, WD_ALIGN_PARAGRAPH.JUSTIFY)
        a = p.add_run("• ")
        style_run(a, 13, True, GOLD)
        b = p.add_run(item)
        style_run(b, 13, False, color)


def answer_lines(doc, count=2):
    for _ in range(count):
        add_text(doc, "........................................................................................................................................................................", 10.5, color="777777", after=0)


def add_question(doc, number, question, answer=None, source=None, lines=2):
    p = doc.add_paragraph()
    paragraph_rtl(p, WD_ALIGN_PARAGRAPH.JUSTIFY)
    n = p.add_run(f"{ar_num(number)} ـ ")
    style_run(n, 12.8, True, NAVY)
    q = p.add_run(question)
    style_run(q, 12.8, True, DARK)
    if source:
        s = p.add_run(f"  ـ {source}")
        style_run(s, 10.5, True, RED)
    if answer is None:
        answer_lines(doc, lines)
    else:
        a = doc.add_paragraph()
        paragraph_rtl(a, WD_ALIGN_PARAGRAPH.JUSTIFY)
        x = a.add_run("الإجابة: ")
        style_run(x, 12.5, True, GREEN)
        y = a.add_run(answer)
        style_run(y, 12.5, False, DARK)


def add_footer(section):
    p = section.footer.paragraphs[0]
    paragraph_rtl(p, WD_ALIGN_PARAGRAPH.CENTER)
    r = p.add_run("أغلى من الذهب ـ الصف الثالث الإعدادي  |  صفحة ")
    style_run(r, 9.2, False, "666666")
    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    r._r.append(begin)
    r._r.append(instr)
    r._r.append(end)


def configure(doc):
    section = doc.sections[0]
    section.orientation = WD_ORIENT.PORTRAIT
    section.top_margin = Cm(1.35)
    section.bottom_margin = Cm(1.35)
    section.right_margin = Cm(1.35)
    section.left_margin = Cm(1.35)
    section.header_distance = Cm(0.55)
    section.footer_distance = Cm(0.55)
    add_footer(section)
    normal = doc.styles["Normal"]
    normal.font.name = "Arial"
    normal.font.size = Pt(13)
    normal._element.rPr.rFonts.set(qn("w:cs"), "Arial")


