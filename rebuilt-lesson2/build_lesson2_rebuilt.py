    doc.add_page_break()
    add_heading_bar(doc, "تدريب ختامي شامل على الدرس", 1)
    add_box(doc, "تعليمات", "أجب عن الأسئلة مستعينًا بالنص كله، واربط بين الفهم والتحليل والتذوق والتطبيق.", fill=BLUE, border=NAVY)
