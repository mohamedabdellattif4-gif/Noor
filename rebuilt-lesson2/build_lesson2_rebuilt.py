AR_DIGITS = str.maketrans("0123456789", "٠١٢٣٤٥٦٧٨٩")


def ar_num(n: int) -> str:
    return str(n).translate(AR_DIGITS)


def set_cell_shading(cell, fill: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = tc_pr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tc_pr.append(shd)
    shd.set(qn("w:fill"), fill)


def set_cell_borders(cell, color: str = NAVY, size: str = "6") -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    borders = tc_pr.find(qn("w:tcBorders"))
    if borders is None:
        borders = OxmlElement("w:tcBorders")
        tc_pr.append(borders)
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        tag = qn(f"w:{edge}")
        elem = borders.find(tag)
        if elem is None:
            elem = OxmlElement(f"w:{edge}")
            borders.append(elem)
        elem.set(qn("w:val"), "single")
        elem.set(qn("w:sz"), size)
        elem.set(qn("w:color"), color)


def set_repeat_table_header(row) -> None:
    tr_pr = row._tr.get_or_add_trPr()
    tbl_header = OxmlElement("w:tblHeader")
    tbl_header.set(qn("w:val"), "true")
    tr_pr.append(tbl_header)


def set_keep_with_next(paragraph, value: bool = True) -> None:
    p_pr = paragraph._p.get_or_add_pPr()
    keep = p_pr.find(qn("w:keepNext"))
    if keep is None and value:
        keep = OxmlElement("w:keepNext")
        p_pr.append(keep)
    elif keep is not None and not value:
        p_pr.remove(keep)


def set_rtl(paragraph) -> None:
    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p_pr = paragraph._p.get_or_add_pPr()
    bidi = p_pr.find(qn("w:bidi"))
    if bidi is None:
        bidi = OxmlElement("w:bidi")
        p_pr.append(bidi)
    bidi.set(qn("w:val"), "1")
    for run in paragraph.runs:
        r_pr = run._r.get_or_add_rPr()
        rtl = r_pr.find(qn("w:rtl"))
        if rtl is None:
            rtl = OxmlElement("w:rtl")
            r_pr.append(rtl)
        rtl.set(qn("w:val"), "1")


def style_run(run, *, size: float = 14, bold: bool = False, color: str = DARK, font: str = "Arial") -> None:
    run.font.name = font
    run.font.size = Pt(size)
    run.bold = bold
    run.font.color.rgb = RGBColor.from_string(color)
    r_pr = run._r.get_or_add_rPr()
    r_fonts = r_pr.find(qn("w:rFonts"))
    if r_fonts is None:
        r_fonts = OxmlElement("w:rFonts")
        r_pr.append(r_fonts)
    for attr in ("ascii", "hAnsi", "cs", "eastAsia"):
        r_fonts.set(qn(f"w:{attr}"), font)
    rtl = r_pr.find(qn("w:rtl"))
    if rtl is None:
        rtl = OxmlElement("w:rtl")
        r_pr.append(rtl)
    rtl.set(qn("w:val"), "1")


def format_paragraph(paragraph, *, before: float = 0, after: float = 6, line: float = 1.25, justify: bool = False) -> None:
    set_rtl(paragraph)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY if justify else WD_ALIGN_PARAGRAPH.RIGHT
    fmt = paragraph.paragraph_format
    fmt.space_before = Pt(before)
    fmt.space_after = Pt(after)
    fmt.line_spacing_rule = WD_LINE_SPACING.SINGLE
    fmt.line_spacing = line


def add_text(doc: Document, text: str, *, size: float = 14, bold: bool = False, color: str = DARK,
             before: float = 0, after: float = 6, justify: bool = False, center: bool = False) -> None:
    p = doc.add_paragraph()
    if center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    else:
        format_paragraph(p, before=before, after=after, justify=justify)
    run = p.add_run(text)
    style_run(run, size=size, bold=bold, color=color)
    if not center:
        set_rtl(p)


def add_heading_bar(doc: Document, text: str, level: int = 1, color: str = NAVY) -> None:
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = True
    cell = table.cell(0, 0)
    set_cell_shading(cell, color)
    set_cell_borders(cell, color, "3")
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    p = cell.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if level == 1 else WD_ALIGN_PARAGRAPH.RIGHT
    set_rtl(p)
    run = p.add_run(text)
    style_run(run, size=19 if level == 1 else 16, bold=True, color=WHITE)
    set_keep_with_next(p)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)


def add_subheading(doc: Document, text: str, color: str = NAVY) -> None:
    p = doc.add_paragraph()
    format_paragraph(p, before=8, after=4)
    p.paragraph_format.keep_with_next = True
    run = p.add_run(text)
    style_run(run, size=15.5, bold=True, color=color)
    p_pr = p._p.get_or_add_pPr()
    borders = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "10")
    bottom.set(qn("w:color"), color)
    borders.append(bottom)
    p_pr.append(borders)


def add_box(doc: Document, title: str, body: str, *, fill: str = BLUE, border: str = NAVY, title_color: str = NAVY) -> None:
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = True
    cell = table.cell(0, 0)
    set_cell_shading(cell, fill)
    set_cell_borders(cell, border, "8")
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    p = cell.paragraphs[0]
    format_paragraph(p, after=3, justify=True)
    r1 = p.add_run(title + ": ")
    style_run(r1, size=14, bold=True, color=title_color)
    r2 = p.add_run(body)
    style_run(r2, size=14, color=DARK)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)


def add_bullets(doc: Document, items: Iterable[str], *, color: str = DARK, size: float = 13.5) -> None:
    for item in items:
        p = doc.add_paragraph()
        format_paragraph(p, after=3, justify=True)
        r1 = p.add_run("• ")
        style_run(r1, size=size, bold=True, color=GOLD)
        r2 = p.add_run(item)
        style_run(r2, size=size, color=color)


def add_table(doc: Document, headers: list[str], rows: list[list[str]], *, header_fill: str = NAVY,
              widths: list[float] | None = None, font_size: float = 11.5) -> None:
    table = doc.add_table(rows=1, cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False if widths else True
    table.style = "Table Grid"
    hdr = table.rows[0]
    set_repeat_table_header(hdr)
    for i, text in enumerate(headers):
        cell = hdr.cells[i]
        set_cell_shading(cell, header_fill)
        set_cell_borders(cell, NAVY, "5")
        if widths:
            cell.width = Cm(widths[i])
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        set_rtl(p)
        run = p.add_run(text)
        style_run(run, size=font_size, bold=True, color=WHITE)
    for r_idx, row_data in enumerate(rows):
        row = table.add_row()
        for i, text in enumerate(row_data):
            cell = row.cells[i]
            set_cell_shading(cell, WHITE if r_idx % 2 == 0 else GRAY)
            set_cell_borders(cell, "A8B9CC", "4")
            if widths:
                cell.width = Cm(widths[i])
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.TOP
            p = cell.paragraphs[0]
            format_paragraph(p, after=0, justify=True)
            run = p.add_run(text)
            style_run(run, size=font_size, color=DARK)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)


def add_questions(doc: Document, questions: list[str], answers: list[str] | None = None, *, source: str | None = None) -> None:
    for i, question in enumerate(questions, 1):
        p = doc.add_paragraph()
        format_paragraph(p, before=2, after=2, justify=True)
        n = p.add_run(f"{ar_num(i)} ـ ")
        style_run(n, size=13, bold=True, color=NAVY)
        q = p.add_run(question)
        style_run(q, size=13, bold=True, color=DARK)
        if source:
            s = p.add_run(f"  المصدر: {source}")
            style_run(s, size=10.5, bold=True, color=RED)
        if answers is None:
            for _ in range(2):
                lp = doc.add_paragraph("................................................................................................................................................")
                format_paragraph(lp, after=0)
                for run in lp.runs:
                    style_run(run, size=11, color="777777")
        else:
            ap = doc.add_paragraph()
            format_paragraph(ap, after=4, justify=True)
            a1 = ap.add_run("الإجابة: ")
            style_run(a1, size=12.5, bold=True, color=GREEN)
            a2 = ap.add_run(answers[i - 1])
            style_run(a2, size=12.5, color=DARK)


def add_footer(section) -> None:
    footer = section.footer
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run("أغلى من الذهب ـ الصف الثالث الإعدادي  |  صفحة ")
    style_run(r, size=9.5, color="666666")
    fld_char1 = OxmlElement("w:fldChar")
    fld_char1.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    fld_char2 = OxmlElement("w:fldChar")
    fld_char2.set(qn("w:fldCharType"), "end")
    r._r.append(fld_char1)
    r._r.append(instr)
    r._r.append(fld_char2)


def configure_document(doc: Document) -> None:
    section = doc.sections[0]
    section.top_margin = Cm(1.5)
    section.bottom_margin = Cm(1.45)
    section.right_margin = Cm(1.6)
    section.left_margin = Cm(1.6)
    section.header_distance = Cm(0.65)
    section.footer_distance = Cm(0.65)
    add_footer(section)
    styles = doc.styles
    normal = styles["Normal"]
    normal.font.name = "Arial"
    normal.font.size = Pt(13)
    normal._element.rPr.rFonts.set(qn("w:cs"), "Arial")


