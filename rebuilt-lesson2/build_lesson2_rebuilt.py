def add_paragraph_unit(doc: Document, item: dict, idx: int, answer: bool) -> None:
    add_heading_bar(doc, f"{ar_num(idx)} ـ {item['title']}", 1)
    add_subheading(doc, "نص الفقرة", color=GOLD)
    add_box(doc, "النص", item["text"], fill=PALE_GOLD, border=GOLD, title_color=GOLD)
    add_box(doc, "الفكرة الجزئية", item["idea"], fill=BLUE, border=NAVY, title_color=NAVY)

    add_subheading(doc, "الشرح التفصيلي")
    add_bullets(doc, item["explanation"], size=13.5)

    add_subheading(doc, "القاموس اللغوي الشامل", color=GOLD)
    add_table(doc, ["الكلمة أو التعبير", "المعنى في السياق", "المضاد", "الجمع", "المفرد"], item["vocab"], header_fill=GOLD, widths=[3.2, 5.4, 3.1, 2.4, 2.4], font_size=10.7)

    add_subheading(doc, "التعبيرات ودلالاتها", color=RED)
    add_table(doc, ["التعبير", "الدلالة والأثر"], item["expressions"], header_fill=RED, widths=[6.0, 10.5], font_size=11.3)

    add_subheading(doc, "القيم والمبادئ مع الدليل", color=GREEN)
    add_table(doc, ["القيمة", "الدليل من الفقرة"], item["values"], header_fill=GREEN, widths=[5.0, 11.5], font_size=11.3)

    add_subheading(doc, "أسئلة الفهم والاستيعاب")
    add_questions(doc, item["qa"], item["qa_answers"] if answer else None)

    add_heading_bar(doc, "أولًا ـ تحليل النص بعد الفقرة", 2, color=NAVY)
    add_table(doc, ["عنصر التحليل", "التطبيق على الفقرة"], item["analysis"], header_fill=NAVY, widths=[4.2, 12.3], font_size=11.3)

    add_heading_bar(doc, "ثانيًا ـ تذوق النص بعد الفقرة", 2, color=RED)
    add_table(doc, ["عنصر التذوق", "التطبيق والأثر"], item["taste"], header_fill=RED, widths=[4.2, 12.3], font_size=11.3)

    add_heading_bar(doc, "تدريب شامل على الفقرة", 2, color=GREEN)
    add_questions(doc, item["exercise"], item["exercise_answers"] if answer else None)
    if idx < len(PARAGRAPHS):
        doc.add_page_break()


