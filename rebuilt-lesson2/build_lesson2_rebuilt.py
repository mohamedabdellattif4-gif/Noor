def add_cover(doc: Document, answer: bool) -> None:
    for _ in range(3):
        doc.add_paragraph()
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = table.cell(0, 0)
    set_cell_shading(cell, NAVY)
    set_cell_borders(cell, NAVY, "10")
    p = cell.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run("الوحدة الأولى ـ الدرس الثاني")
    style_run(r, size=20, bold=True, color=WHITE)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run("أَغْلَى مِنَ الذَّهَبِ")
    style_run(r, size=30, bold=True, color=GOLD)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run("شرح موسع وتحليل النص وتذوقه بعد كل فقرة")
    style_run(r, size=17, bold=True, color=NAVY)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run("نموذج الإجابة" if answer else "نسخة الطالب")
    style_run(r, size=22, bold=True, color=GREEN if answer else RED)
    add_box(doc, "منهج العمل", "بعد كل فقرة مباشرة: شرح تفصيلي، قاموس، تعبيرات ودلالات، قيم، أسئلة فهم، تحليل النص، تذوق النص، ثم تدريب تطبيقي.", fill=PALE_GOLD, border=GOLD, title_color=GOLD)
