def setup_document(title: str):
    doc = Document()
    sec = doc.sections[0]
    sec.top_margin = Cm(1.4)
    sec.bottom_margin = Cm(1.4)
    sec.left_margin = Cm(1.5)
    sec.right_margin = Cm(1.5)
    sec.header_distance = Cm(0.6)
    sec.footer_distance = Cm(0.6)
    styles = doc.styles
    normal = styles["Normal"]
    normal.font.name = "Arial"
    normal.font.size = Pt(13)
    normal.paragraph_format.line_spacing = 1.25
    header = sec.header.paragraphs[0]
    header.alignment = WD_ALIGN_PARAGRAPH.CENTER
    hr = header.add_run(title)
    set_run(hr, 10.5, True, TEAL)
    add_bidi(header)
    footer = sec.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    fr = footer.add_run("الصف الثالث الإعدادي ـ اللغة العربية")
    set_run(fr, 9.5, False, GREY)
    add_bidi(footer)
    return doc


