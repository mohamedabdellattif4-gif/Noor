def add_bidi(paragraph):
    p_pr = paragraph._p.get_or_add_pPr()
    bidi = p_pr.find(qn("w:bidi"))
    if bidi is None:
        bidi = OxmlElement("w:bidi")
        bidi.set(qn("w:val"), "1")
        p_pr.append(bidi)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    for run in paragraph.runs:
        r_pr = run._r.get_or_add_rPr()
        rtl = r_pr.find(qn("w:rtl"))
        if rtl is None:
            rtl = OxmlElement("w:rtl")
            rtl.set(qn("w:val"), "1")
            r_pr.append(rtl)
        r_fonts = r_pr.find(qn("w:rFonts"))
        if r_fonts is None:
            r_fonts = OxmlElement("w:rFonts")
            r_pr.append(r_fonts)
        for attr in ("ascii", "hAnsi", "cs"):
            r_fonts.set(qn(f"w:{attr}"), "Arial")


def set_run(run, size=14, bold=False, color=DARK):
    run.font.name = "Arial"
    run.font.size = Pt(size)
    run.bold = bold
    run.font.color.rgb = RGBColor.from_string(color)
    r_pr = run._r.get_or_add_rPr()
    rtl = r_pr.find(qn("w:rtl"))
    if rtl is None:
        rtl = OxmlElement("w:rtl")
        rtl.set(qn("w:val"), "1")
        r_pr.append(rtl)
    r_fonts = r_pr.find(qn("w:rFonts"))
    if r_fonts is None:
        r_fonts = OxmlElement("w:rFonts")
        r_pr.append(r_fonts)
    for attr in ("ascii", "hAnsi", "cs"):
        r_fonts.set(qn(f"w:{attr}"), "Arial")


def shade_cell(cell, fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = tc_pr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tc_pr.append(shd)
    shd.set(qn("w:fill"), fill)


def set_cell_margins(cell, top=90, start=110, bottom=90, end=110):
    tc = cell._tc
    tc_pr = tc.get_or_add_tcPr()
    tc_mar = tc_pr.first_child_found_in("w:tcMar")
    if tc_mar is None:
        tc_mar = OxmlElement("w:tcMar")
        tc_pr.append(tc_mar)
    for m, v in (("top", top), ("start", start), ("bottom", bottom), ("end", end)):
        node = tc_mar.find(qn(f"w:{m}"))
        if node is None:
            node = OxmlElement(f"w:{m}")
            tc_mar.append(node)
        node.set(qn("w:w"), str(v))
        node.set(qn("w:type"), "dxa")


def set_table_rtl(table):
    table.alignment = WD_TABLE_ALIGNMENT.RIGHT
    tbl_pr = table._tbl.tblPr
    bidi = tbl_pr.find(qn("w:bidiVisual"))
    if bidi is None:
        bidi = OxmlElement("w:bidiVisual")
        bidi.set(qn("w:val"), "1")
        tbl_pr.append(bidi)
    for row in table.rows:
        for cell in row.cells:
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            set_cell_margins(cell)
            for p in cell.paragraphs:
                add_bidi(p)


def add_paragraph(doc, text="", size=14, bold=False, color=DARK, align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=4):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.25
    r = p.add_run(text)
    set_run(r, size=size, bold=bold, color=color)
    add_bidi(p)
    return p


def add_title_bar(doc, text, level=1, fill=TEAL, color=WHITE):
    t = doc.add_table(rows=1, cols=1)
    set_table_rtl(t)
    t.autofit = True
    cell = t.cell(0, 0)
    shade_cell(cell, fill)
    p = cell.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    set_run(r, size=18 if level == 1 else 15, bold=True, color=color)
    add_bidi(p)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)


def add_box(doc, text, fill=PALE_BLUE, border=TEAL, bold=False, size=14):
    t = doc.add_table(rows=1, cols=1)
    set_table_rtl(t)
    cell = t.cell(0, 0)
    shade_cell(cell, fill)
    tc_pr = cell._tc.get_or_add_tcPr()
    borders = tc_pr.find(qn("w:tcBorders"))
    if borders is None:
        borders = OxmlElement("w:tcBorders")
        tc_pr.append(borders)
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        tag = borders.find(qn(f"w:{edge}"))
        if tag is None:
            tag = OxmlElement(f"w:{edge}")
            borders.append(tag)
        tag.set(qn("w:val"), "single")
        tag.set(qn("w:sz"), "10")
        tag.set(qn("w:color"), border)
    p = cell.paragraphs[0]
    r = p.add_run(text)
    set_run(r, size=size, bold=bold, color=DARK)
    add_bidi(p)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)


def add_rtl_table(doc, headers: list[str], rows: Iterable[Iterable[str]], widths=None, header_fill=TEAL):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    set_table_rtl(table)
    hdr = table.rows[0].cells
    for i, h in enumerate(headers):
        shade_cell(hdr[i], header_fill)
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(h)
        set_run(r, size=12, bold=True, color=WHITE)
        add_bidi(p)
    for ri, row in enumerate(rows):
        cells = table.add_row().cells
        for i, value in enumerate(row):
            if ri % 2 == 1:
                shade_cell(cells[i], "F4FAFB")
            p = cells[i].paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            r = p.add_run(str(value))
            set_run(r, size=11.5, color=DARK)
            add_bidi(p)
    if widths:
        for row in table.rows:
            for idx, width in enumerate(widths):
                row.cells[idx].width = Cm(width)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return table


def add_question(doc, number, question, source=None, answer=None, student=True, lines=2):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(2)
    r = p.add_run(f"{number} ـ {question}")
    set_run(r, 13, True, TEAL)
    add_bidi(p)
    if source:
        sp = doc.add_paragraph()
        sr = sp.add_run(source)
        set_run(sr, 10.5, True, RED)
        add_bidi(sp)
    if student:
        for _ in range(lines):
            lp = doc.add_paragraph("................................................................................................................................................")
            lp.paragraph_format.space_after = Pt(0)
            lr = lp.runs[0]
            set_run(lr, 10, False, GREY)
            add_bidi(lp)
    elif answer is not None:
        ap = doc.add_paragraph()
        ar = ap.add_run("الإجابة: " + answer)
        set_run(ar, 12.5, True, GREEN)
        add_bidi(ap)


